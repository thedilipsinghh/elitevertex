import { pgTable, uuid, varchar, timestamp, text, boolean } from "drizzle-orm/pg-core";

export const websiteSettings = pgTable("website_settings", {
  id: uuid("id").defaultRandom().primaryKey(),
  instituteName: varchar("institute_name", { length: 255 }),
  heroTagline: text("hero_tagline"),
  heroTitle: text("hero_title"),
  heroSubtitle: text("hero_subtitle"),
  heroImage: text("hero_image"),
  callToActionTitle: text("cta_title"),
  callToActionSubtitle: text("cta_subtitle"),
  phone: varchar("phone", { length: 100 }),
  whatsapp: varchar("whatsapp", { length: 100 }),
  email: varchar("email", { length: 255 }),
  address: text("address"),
  workingHours: text("working_hours"),
  googleMapsUrl: text("google_maps_url"),
  facebookUrl: text("facebook_url"),
  instagramUrl: text("instagram_url"),
  footerText: text("footer_text"),
  contactTitle: text("contact_title"),
  contactSubtitle: text("contact_subtitle"),
  contactTagline: text("contact_tagline"),
  logoUrl: text("logo_url"),
  faviconUrl: text("favicon_url"),
  linkedinUrl: text("linkedin_url"),
  youtubeUrl: text("youtube_url"),
  announcementEnabled: boolean("announcement_enabled").default(false).notNull(),
  announcementText: text("announcement_text"),
  announcementLink: text("announcement_link"),
  seoMetaTitle: varchar("seo_meta_title", { length: 255 }),
  seoMetaDescription: text("seo_meta_description"),
  certSig1Name: varchar("cert_sig1_name", { length: 255 }),
  certSig1Title: varchar("cert_sig1_title", { length: 255 }),
  certSig1Sign: text("cert_sig1_sign"),
  certSig2Name: varchar("cert_sig2_name", { length: 255 }),
  certSig2Title: varchar("cert_sig2_title", { length: 255 }),
  certSig2Sign: text("cert_sig2_sign"),
  certShowcaseEnabled: boolean("cert_showcase_enabled").default(true),
  certShowcaseTitle: text("cert_showcase_title"),
  certShowcaseSubtitle: text("cert_showcase_subtitle"),
  certShowcaseStudentName: varchar("cert_showcase_student_name", { length: 255 }),
  certShowcaseCourseName: varchar("cert_showcase_course_name", { length: 255 }),
  certShowcaseCertNumber: varchar("cert_showcase_cert_number", { length: 100 }),
  certShowcaseIssueDate: varchar("cert_showcase_issue_date", { length: 100 }),
  certShowcaseGrade: varchar("cert_showcase_grade", { length: 100 }),
  certShowcaseBadgeText: varchar("cert_showcase_badge_text", { length: 100 }),
  socialStickyEnabled: boolean("social_sticky_enabled").default(true),
  socialStickyPosition: varchar("social_sticky_position", { length: 20 }).default("right"),
  socialStickyOffset: varchar("social_sticky_offset", { length: 20 }).default("center"),
  socialShowInstagram: boolean("social_show_instagram").default(true),
  socialShowFacebook: boolean("social_show_facebook").default(true),
  socialShowWhatsapp: boolean("social_show_whatsapp").default(true),
  updatedAt: timestamp("updated_at").defaultNow().notNull(),
});

